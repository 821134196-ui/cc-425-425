CONCRETE = (217, 217, 215)
DARK = (26, 26, 26)
TEAL = (20, 184, 166)
LIGHT = (245, 245, 243)
WARN = (220, 90, 60)


class _Canvas:
    def __init__(self, w: int, h: int, bg: tuple[int, int, int]):
        self.w, self.h = w, h
        self.px = bytearray(bg * w * h)

    def set(self, x: int, y: int, c: tuple[int, int, int]) -> None:
        if 0 <= x < self.w and 0 <= y < self.h:
            i = (y * self.w + x) * 3
            self.px[i:i + 3] = bytes(c)

    def rect(self, x: int, y: int, w: int, h: int, c: tuple[int, int, int]) -> None:
        for j in range(y, y + h):
            for i in range(x, x + w):
                self.set(i, j, c)

    def text(
        self, s: str, x: int, y: int, scale: int, c: tuple[int, int, int]
    ) -> int:
        cursor = x
        for ch in s.upper():
            glyph = _FONT.get(ch, _FONT["?"])
            for row, bits in enumerate(glyph):
                for col, b in enumerate(bits):
                    if b == "1":
                        self.rect(cursor + col * scale, y + row * scale, scale, scale, c)
            cursor += 6 * scale
        return cursor - x

    def to_png(self) -> bytes:
        raw = bytearray()
        stride = self.w * 3
        for y in range(self.h):
            raw.append(0)
            raw.extend(self.px[y * stride:(y + 1) * stride])
        comp = zlib.compress(bytes(raw), 9)

        def chunk(tag: bytes, data: bytes) -> bytes:
            return (
                struct.pack(">I", len(data))
                + tag
                + data
                + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)
            )

        return (
            b"\x89PNG\r\n\x1a\n"
            + chunk(b"IHDR", struct.pack(">IIBBBBB", self.w, self.h, 8, 2, 0, 0, 0))
            + chunk(b"IDAT", comp)
            + chunk(b"IEND", b"")
        )


def make_evidence(
    path: str | Path,
    *,
    lane_code: str,
    direction: str,
    device_time: str,
    plate: str | None,
    confidence: float,
    flagged: bool = False,
) -> Path:
    """生成一张车道抓拍证据 PNG，返回写入路径。"""
    w, h = 640, 250
    cv = _Canvas(w, h, CONCRETE)
    # 顶部黑色设备信息条 + 青绿侧标
    cv.rect(0, 0, w, 34, DARK)
    cv.rect(0, 0, 8, 34, TEAL)
    cv.text(f"CAM {lane_code} {direction}", 18, 6, 2, LIGHT)
    cv.text(device_time.replace("-", ".")[2:], 418, 6, 2, TEAL)
    # 模拟车头轮廓（简笔）
    cv.rect(60, 90, 220, 90, (150, 150, 148))
    cv.rect(80, 70, 180, 30, (120, 120, 118))
    cv.rect(92, 76, 156, 18, (190, 215, 214))
    cv.rect(60, 176, 220, 8, (90, 90, 88))
    # 车牌框
    plate_box_y = 120
    cv.rect(310, plate_box_y, 290, 56, (24, 64, 140))
    cv.rect(310, plate_box_y, 14, 56, TEAL if not flagged else WARN)
    label = plate if plate else "NO PLATE"
    cv.text(label, 332, plate_box_y + 17, 3, LIGHT)
    # 置信度与识别状态
    conf_color = TEAL if confidence >= 0.9 and not flagged else WARN
    cv.text(f"CONF {confidence * 100:05.2f}%", 312, 190, 2, DARK)
    status = "MATCH OK" if not flagged else "REVIEW REQUIRED"
    cv.text(status, 312, 212, 2, conf_color)
    cv.text("EVIDENCE IMAGE - FICTIONAL DEMO DATA", 18, 228, 1, (90, 90, 88))

    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(cv.to_png())
    return path
